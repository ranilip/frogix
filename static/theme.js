function applyTheme(name, save) {
  const vars = THEMES[name] || THEMES.ocean;
  const root = document.documentElement;
  for (const [k, v] of Object.entries(vars)) root.style.setProperty(k, v);
  if (save) {
    try { localStorage.setItem('ui-theme', name in THEMES ? name : 'ocean'); } catch (_) {}
  }
}

(function () {
  try {
    const saved = localStorage.getItem('ui-theme');
    if (saved && saved in THEMES) applyTheme(saved, false);
  } catch (_) {}
})();
